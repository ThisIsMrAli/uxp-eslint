// Generates docs/rules/*.md and docs/rules/README.md from rule metadata (dist/) and docs/src/rule-docs.mjs.
// Usage: npm run build && node scripts/gen-docs.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import plugin from "../dist/index.js";
import { JS_RECOMMENDED, JS_PHOTOSHOP, JS_STRICT, CSS_RULES, CSS_STRICT, HTML_RULES, MANIFEST_RULES } from "../dist/configs.js";
import { RULES } from "../docs/src/rule-docs.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "docs/rules");
const sev = (map, name) => { const v = map[`uxp-lint/${name}`]; return v === undefined ? null : Array.isArray(v) ? v[0] : v; };
const level = (name) => sev(JS_RECOMMENDED, name) ?? sev(JS_PHOTOSHOP, name) ?? sev(CSS_RULES, name) ?? sev(HTML_RULES, name) ?? sev(MANIFEST_RULES, name) ?? "off";
const strictLevel = (name) => sev(JS_STRICT, name) ?? sev(JS_PHOTOSHOP, name) ?? sev(CSS_STRICT, name) ?? sev(HTML_RULES, name) ?? sev(MANIFEST_RULES, name) ?? "off";
const lang = (ex) => (/\.css$/.test(ex.filename ?? "") ? "css" : /\.html?$/.test(ex.filename ?? "") ? "html" : /\.json$/.test(ex.filename ?? "") ? "json" : /<\w/.test(ex.code) ? "jsx" : "js");
const block = (ex) => {
  const m = ex.manifest ? `<sub>manifest: \`host ${ex.manifest.host.app} ${ex.manifest.host.minVersion}\`${ex.manifest.requiredPermissions ? `, \`requiredPermissions: ${JSON.stringify(ex.manifest.requiredPermissions)}\`` : ""}${ex.manifest.featureFlags ? `, \`featureFlags: ${JSON.stringify(ex.manifest.featureFlags)}\`` : ""}</sub>\n\n` : "";
  return `${m}\`\`\`${lang(ex)}\n${ex.code}\n\`\`\``;
};
const schemaRows = (schema) => {
  const props = schema?.[0]?.properties ?? {};
  const keys = Object.keys(props);
  if (!keys.length) return "This rule has no options.";
  return ["| Option | Type |", "|---|---|", ...keys.map((k) => `| \`${k}\` | ${props[k].type === "array" ? `${props[k].items?.type ?? "any"}[]` : props[k].type} |`)].join("\n");
};

const index = [];
for (const [name, rule] of Object.entries(plugin.rules).sort(([a], [b]) => a.localeCompare(b))) {
  const d = RULES[name];
  if (!d) throw new Error(`docs/src/rule-docs.mjs has no entry for ${name}`);
  const meta = rule.meta;
  const badges = [
    `**Type:** ${meta.type}`,
    `**Recommended:** ${level(name)}`,
    `**Strict:** ${strictLevel(name)}`,
    meta.fixable ? "**Autofix:** yes (`--fix`)" : null,
    meta.hasSuggestions ? "**Suggestions:** yes (editor quick fix)" : null,
  ].filter(Boolean).join(" · ");
  const msgs = Object.entries(meta.messages).map(([id, text]) => `- \`${id}\`: ${text}`).join("\n");
  const sources = (meta.docs.sources ?? []).map((s) => `- ${/^https?:/.test(s) ? `<${s}>` : s}`).join("\n");
  const md = `<!-- Generated by scripts/gen-docs.mjs from rule metadata and docs/src/rule-docs.mjs. Do not edit by hand. -->
# uxp-lint/${name}

${meta.docs.description}.

${badges}

## What it checks

${d.details}

## Examples

### Incorrect

${d.incorrect.map(block).join("\n\n")}

### Correct

${d.correct.map(block).join("\n\n")}

## Options

${schemaRows(meta.schema)}

## Messages

${msgs}

## When not to use it

${d.whenNot}

## Sources

${sources}
`;
  fs.writeFileSync(path.join(out, `${name}.md`), md);
  index.push(`| [\`${name}\`](./${name}.md) | ${meta.docs.description} | ${level(name)} | ${meta.fixable ? "🔧" : ""}${meta.hasSuggestions ? "💡" : ""} |`);
}
fs.writeFileSync(path.join(out, "README.md"), `<!-- Generated by scripts/gen-docs.mjs. Do not edit by hand. -->
# Rules

🔧 autofix with \`--fix\` · 💡 editor suggestion. Severity is for the \`recommended\` preset; \`strict\` raises most warnings to errors.

| Rule | Description | Recommended | |
|---|---|---|---|
${index.join("\n")}
`);
console.log(`wrote ${index.length} rule pages`);
