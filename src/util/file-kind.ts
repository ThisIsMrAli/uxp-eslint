/**
 * Browser-safe file classification shared by every rule.
 * Generated or minified bundles and Node-only scripts are not UXP source a developer edits, so rules skip them
 * (override with settings.uxp.lintGenerated / settings.uxp.lintNodeScripts).
 */
const cache = new WeakMap<object, FileKind>();
export type FileKind = "source" | "generated" | "node";

const GENERATED_BANNER = /^\s*(\/\*[!*]?\s*)?(@generated|generated by|auto-?generated|this file (is|was) (auto-?)?generated|do not edit)/i;

export function classifySource(text: string, filename: string): FileKind {
  if (/(^|\/)manifest\.json$/.test(filename)) return "source";
  const head = text.slice(0, 600);
  if (GENERATED_BANNER.test(head) || /\.min\.(js|css|mjs)$/.test(filename) || /(^|\/)(sourcemap|.*\.map)$/.test(filename)) return "generated";
  // Minified: very long lines, or a high average line length over a non-trivial file.
  let longest = 0;
  let lines = 1;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) === 10) { longest = Math.max(longest, i - start); start = i + 1; lines++; }
  }
  longest = Math.max(longest, text.length - start);
  if (longest > 3000 || (text.length > 2000 && text.length / lines > 300)) return "generated";
  if (/\.(c|m)?(j|t)sx?$|\.(ps|id)js$/.test(filename)) {
    if (text.startsWith("#!")) return "node"; // CLI script
    // UXP's module loader has no `node:` scheme, so a file importing node:* is Node tooling (tests, build scripts).
    if (/(?:^|[\s;(=])(?:import\s[^;]*?from\s*|import\s*\(\s*|require\s*\(\s*|import\s+)["']node:[a-z_/]+["']/m.test(text)) return "node";
    // Command-line scripts: UXP plugins have no argv, exit code or stdio.
    if (/\bprocess\.(argv|exit|stdout|stderr|stdin)\b|\brequire\.main\s*===\s*module\b|\bimport\.meta\.(dirname|filename|main)\b/.test(text)) return "node";
  }
  return "source";
}

/** Classification for the file the rule context is linting (cached per SourceCode). */
export function fileKind(context: { sourceCode?: { text: string }; getSourceCode?: () => { text: string }; filename?: string; getFilename?: () => string }): FileKind {
  const sc = context.sourceCode ?? context.getSourceCode?.();
  if (!sc) return "source";
  const hit = cache.get(sc);
  if (hit) return hit;
  const filename = (context.filename ?? context.getFilename?.() ?? "").split("\\").join("/");
  const kind = classifySource(sc.text, filename);
  cache.set(sc, kind);
  return kind;
}
